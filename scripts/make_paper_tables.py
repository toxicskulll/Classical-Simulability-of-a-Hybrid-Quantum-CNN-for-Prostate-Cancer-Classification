def s_phase(tag: str, folder: str, what: str, ref_name: str) -> None:
    pooled, dl, cv = load_phase(folder)
    leak = any(cv.model == "clin_lr_gleason_leakref")
    rows = [[NAMES[r.model], params(r.model)] + [pm(getattr(r, f"{k}_mean"), getattr(r, f"{k}_std")) for k, _ in METRICS]
            for r in cv.itertuples()]
    src = [f"results/{folder}/cv_metrics.csv", "results/param_counts.csv"]
    n_seeds, n_folds = int(cv.n_seeds.iloc[0]), int(cv.n_folds.iloc[0])
    table(f"s_{tag}_cv", src, f"{what}: per-fold metrics, mean $\\pm$ SD over {n_folds} seed--fold cells "
          f"({n_seeds} seeds); thresholds F1-optimal on each training fold.",
          ["Model", "Parameters"] + [h for _, h in METRICS], rows, wrap("3.6cm") + "c" * 7, size=TIGHT,
          note=LEAK_NOTE if leak else None)
    rows = []
    for r in pooled.itertuples():
        g = dl[dl.comparator == r.model]
        if g.empty:
            rows.append([NAMES[r.model], pm(r.pooled_AUC_mean, r.pooled_AUC_std), ci(r.ci95_lo, r.ci95_hi),
                         "reference", "--", "--"])
            continue
        q = g.iloc[0]
        rows.append([NAMES[r.model], pm(r.pooled_AUC_mean, r.pooled_AUC_std), ci(r.ci95_lo, r.ci95_hi),
                     f"{num(q.delta_AUC_mean, sign=True)} {ci(q.delta_ci95_lo, q.delta_ci95_hi, sign=True)}",
                     f"{pval(q.delong_p_median)} ({pval(q.delong_p_min)}--{pval(q.delong_p_max)})",
                     f"{integer(q.seeds_p_lt_005)}/{integer(q.n_seeds)}"])
    table(f"s_{tag}_comparisons", [f"results/{folder}/pooled_auc.csv", f"results/{folder}/delong.csv"],
          f"{what}: pooled out-of-fold AUC (mean $\\pm$ SD over seeds, patient-level bootstrap 95\\% CI) and "
          f"paired comparison with {ref_name}.",
          ["Model", "Pooled AUC", "95\\% CI", "$\\Delta$AUC [95\\% CI]", "DeLong $p$, median (range)",
           "Seeds $p<0.05$"], rows, wrap("3.6cm") + "ccccc", size=TIGHT,
          note=f"$\\Delta$AUC = {ref_name} $-$ model. " + (LEAK_NOTE if leak else ""))



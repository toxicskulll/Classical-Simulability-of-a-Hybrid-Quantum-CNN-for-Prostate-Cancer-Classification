# ── number formatting (siunitx) ──────────────────────────────────────────────
def num(x, d: int = 3, sign: bool = False) -> str:
    if x is None or pd.isna(x):
        return "--"
    return f"\\num{{{x:+.{d}f}}}" if sign else f"\\num{{{x:.{d}f}}}"


def integer(x) -> str:
    return "--" if x is None or pd.isna(x) else f"\\num{{{int(round(float(x)))}}}"


def sci(x, d: int = 1) -> str:
    return "\\num{0}" if x == 0 else f"\\num{{{x:.{d}e}}}"


def ci(lo, hi, d: int = 3, sign: bool = False) -> str:
    return f"[{num(lo, d, sign)}, {num(hi, d, sign)}]"


def pm(m, s, d: int = 3) -> str:
    return f"\\num{{{m:.{d}f} \\pm {s:.{d}f}}}"


def pval(p: float) -> str:
    return f"\\num{{{p:.1e}}}" if p < 1e-3 else f"\\num{{{p:.3f}}}"


# ── writer ───────────────────────────────────────────────────────────────────
def _tabular(header, rows, align) -> list[str]:
    out = [f"\\begin{{tabular}}{{{align}}}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule"]
    out += [r if isinstance(r, str) else " & ".join(r) + " \\\\" for r in rows]
    return out + ["\\bottomrule", "\\end{tabular}"]


def table(name: str, sources: list[str], caption: str, header=None, rows=None, align: str | None = None,
          note: str | None = None, size: str = "\\small", parts: list | None = None) -> None:
    """One table float. `parts` = [(title, header, rows, align), ...] stacks several tabulars
    under one caption; a row given as a string is written verbatim (e.g. a sub-heading)."""
    parts = parts or [(None, header, rows, align or "l" + "c" * (len(header) - 1))]
    label = "tab:" + name
    lines = [f"% generated by scripts/make_paper_tables.py from: {', '.join(sources)}",
             "\\begin{table}[tbp]", "\\centering", f"\\caption{{{caption}}}", f"\\label{{{label}}}", size]
    for i, (title, h, r, a) in enumerate(parts):
        if title:
            lines += ["\\par\\smallskip" if i else "", f"{{\\itshape {title}}}\\par\\smallskip"]
        lines += _tabular(h, r, a or "l" + "c" * (len(h) - 1))
    if note:
        lines.append(f"\\par\\smallskip{{\\footnotesize {note}\\par}}")
    lines += ["\\end{table}", ""]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.tex").write_text("\n".join(lines), encoding="utf-8")
    print(f"  {name}.tex  <- {', '.join(sources)}")


def wrap(width: str) -> str:
    """Left-aligned first column that wraps at `width` (needs the array package)."""
    return f">{{\\raggedright\\arraybackslash}}p{{{width}}}"


TIGHT = "\\scriptsize\\setlength{\\tabcolsep}{3pt}"


def subhead(text: str, ncol: int) -> str:
    return f"\\multicolumn{{{ncol}}}{{l}}{{\\itshape {text}}} \\\\"


# ── shared loaders ───────────────────────────────────────────────────────────
def load_phase(folder: str):
    d = R / folder
    return pd.read_csv(d / "pooled_auc.csv"), pd.read_csv(d / "delong.csv"), pd.read_csv(d / "cv_metrics.csv")


PARAMS = None


def params(model: str) -> str:
    global PARAMS
    if PARAMS is None:
        PARAMS = pd.read_csv(R / "param_counts.csv").set_index("model")
    if model not in PARAMS.index or PARAMS.loc[model, "n_cells_with_count"] == 0:
        return "--"
    r = PARAMS.loc[model]
    if r.n_params_min == r.n_params_max:
        return integer(r.n_params_min)
    return f"{integer(r.n_params_median)} ({integer(r.n_params_min)}--{integer(r.n_params_max)})"


def auc_cell(r) -> str:
    return f"{num(r.pooled_AUC_mean)} {ci(r.ci95_lo, r.ci95_hi)}"


def delta_cell(dl: pd.DataFrame, model: str) -> str:
    g = dl[dl.comparator == model]
    if g.empty:
        return "reference"
    r = g.iloc[0]
    return f"{num(r.delta_AUC_mean, sign=True)} {ci(r.delta_ci95_lo, r.delta_ci95_hi, sign=True)}"



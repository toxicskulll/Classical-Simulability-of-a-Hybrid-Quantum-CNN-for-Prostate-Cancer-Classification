def main_results() -> None:
    pooled, dl, _ = load_phase("tables_phase3")
    order = ["hqcnn_tuned", "dephased_tuned", "tree_net_tuned", "mlp_matched_tuned", "lr_tuned", "svm_tuned",
             "rf_tuned", "hqcnn", "clin_lr_prebiopsy", "clin_lr_gleason_leakref"]
    names = dict(NAMES, hqcnn="HQCNN (untuned)")
    rows = []
    for m in order:
        if m == "hqcnn":
            rows.append("\\midrule")
        r = pooled[pooled.model == m].iloc[0]
        rows.append([names[m], params(m), auc_cell(r), delta_cell(dl, m)])
    n_seeds, n_boot = int(pooled.n_seeds.iloc[0]), int(pooled.n_boot.iloc[0])
    table("main_results", ["results/tables_phase3/pooled_auc.csv", "results/tables_phase3/delong.csv",
                           "results/param_counts.csv"],
          f"Clinical benchmark on PROSTATEx after nested tuning: pooled out-of-fold AUC (mean over {n_seeds} seeds) "
          f"with patient-level bootstrap 95\\% CIs ({n_boot} resamples).",
          ["Model", "Parameters", "Pooled AUC [95\\% CI]", "$\\Delta$AUC [95\\% CI]"], rows, "lccc",
          note="$\\Delta$AUC = tuned HQCNN $-$ model, paired on the same lesions and resamples. Parameters: median "
               "(min--max) over the seed--fold cells, because tuned models choose their size per outer fold; "
               "-- non-parametric. " + LEAK_NOTE)


